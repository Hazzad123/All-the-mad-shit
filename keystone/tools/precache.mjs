#!/usr/bin/env node
/* Writes precache.js: every file the site needs offline, plus a version hash of their contents.
 * The service worker (sw.js) loads it and caches every file on install, so the site works offline
 * after the first visit. Re-run after adding, removing or changing files:
 *   node tools/precache.mjs           → rewrite precache.js
 *   node tools/precache.mjs --check   → exit 1 if precache.js is out of date (used by CI) */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const list = (dir, ext) => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith(ext)).sort().map(f => dir + '/' + f);

const files = [
  './', 'index.html', 'pocket.html', 'manifest.webmanifest',
  ...list('css', '.css'),
  ...list('icons', '.svg'), ...list('icons', '.png'),
  ...list('js/core', '.js'), 'js/studio/app.js', 'js/pocket/app.js',
  ...list('content', '.js'), ...list('content/modules', '.js'),
  ...list('js/labs', '.js'),
];

const hash = crypto.createHash('sha256');
for (const f of files) if (f !== './') hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 12);

const out = `/* Generated by tools/precache.mjs — do not edit by hand. Re-run it after changing any file. */
self.PRECACHE_VERSION = '${version}';
self.PRECACHE = ${JSON.stringify(files, null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '"\n]')};
`;

const target = path.join(root, 'precache.js');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) { console.error('✗ precache.js is out of date — run: node tools/precache.mjs'); process.exit(1); }
  console.log(`✓ precache.js is up to date (${files.length} files, version ${version})`);
} else {
  fs.writeFileSync(target, out);
  console.log(`Wrote precache.js: ${files.length} files, version ${version}`);
}
