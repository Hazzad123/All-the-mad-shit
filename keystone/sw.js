/* Keystone service worker.
   On install it caches every file the site needs (listed in precache.js, generated by tools/precache.mjs),
   so the whole site works offline after the first visit. Requests go to the network first, so updates
   show up straight away; the cache is only used when there is no connection. */
importScripts('precache.js');
const CACHE = 'keystone-' + self.PRECACHE_VERSION;

self.addEventListener('install', e => {
  self.skipWaiting();
  // Cache files one by one, so a single failure doesn't leave the whole cache empty.
  e.waitUntil(caches.open(CACHE).then(c => Promise.all(self.PRECACHE.map(u => c.add(u).catch(() => {})))));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('keystone-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const req = e.request; const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    try {
      const res = await fetch(req);
      if (res && res.ok) cache.put(req, res.clone());
      return res;
    } catch (err) {
      return (await cache.match(req)) || (await cache.match(req, { ignoreSearch: true })) || (await cache.match('index.html')) || new Response('Offline', { status: 503 });
    }
  })());
});

// The pages ask whether everything is cached before they claim to work offline.
self.addEventListener('message', e => {
  if (!e.data || e.data.type !== 'offline-status') return;
  e.waitUntil(caches.open(CACHE).then(c => Promise.all(self.PRECACHE.map(u => c.match(u)))).then(hits => {
    const missing = hits.filter(h => !h).length;
    e.source && e.source.postMessage({ type: 'offline-status', ready: missing === 0, missing, total: hits.length });
  }));
});
